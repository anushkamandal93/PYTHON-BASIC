## TYPE CONVERSION------------------------------------------------------------------------------------------------------
#-->Type conversion is the process of changing a value from one data type to another 

##TYPES
#1. explicit
#--> convert by user
a="24"
b=int(a)
print(b)
print(type(b))

#2.implicit
#-->convert datatype automatically
a=25
b=(a/2)
print(b)
print(type(b))
